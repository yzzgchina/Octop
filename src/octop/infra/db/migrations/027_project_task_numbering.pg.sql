-- Schema v27: project task numbering, multi-subject assignment, comment quotes.
--
-- Canonical v26 -> v27 DDL for PostgreSQL. Executed statement-by-statement by
-- ``_apply_postgresql_migration`` (split on ";\n"), so every statement must be
-- self-contained -- no ``DO $$ ... $$`` block. ``IF NOT EXISTS`` keeps a re-run
-- safe; the data backfill still lives in ``migrate.py``'s
-- ``_backfill_project_task_numbering`` because it has no cross-dialect SQL form.
--
-- Same five groups as the SQLite twin:
--   (a) ``projects.task_prefix``.
--   (b) ``project_tasks.task_number`` + ``project_task_counters`` + the
--       in-project unique index (PLAN §B1.2).
--   (c) ``project_task_owners`` / ``project_task_executors`` (PLAN §B2.3.1).
--       The withdrawn single-value ``project_tasks.owner_user_id`` /
--       ``project_tasks.executor`` columns are NOT created (PLAN §B2.1b).
--   (d) ``project_comments.parent_comment_id`` / ``quote_excerpt`` (PLAN §B3.1).
--
-- New tables in this same pair do NOT raise ``_schema_version`` further
-- (PLAN §B2.3.3).

ALTER TABLE projects ADD COLUMN IF NOT EXISTS task_prefix TEXT NOT NULL DEFAULT '';

ALTER TABLE project_tasks ADD COLUMN IF NOT EXISTS task_number TEXT;
CREATE TABLE IF NOT EXISTS project_task_counters (
  project_id TEXT PRIMARY KEY REFERENCES projects(project_id) ON DELETE CASCADE,
  last_seq   INTEGER NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_project_tasks_number
  ON project_tasks(project_id, task_number);

-- No ``CHECK (subject_type IN ('agent','team'))`` -- see the SQLite twin and
-- PLAN §B2.3.1: the value domain stays a single repo-layer validation point.
-- ``user_id ... ON DELETE CASCADE``: lead ruling 2026-09-30 (PLAN §B2.3.1);
-- see the SQLite twin for the three reasons.
CREATE TABLE IF NOT EXISTS project_task_owners (
  id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id TEXT NOT NULL REFERENCES project_tasks(task_id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  UNIQUE(task_id, user_id)
);
CREATE INDEX IF NOT EXISTS idx_project_task_owners_user ON project_task_owners(user_id);

CREATE TABLE IF NOT EXISTS project_task_executors (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id      TEXT NOT NULL REFERENCES project_tasks(task_id) ON DELETE CASCADE,
  subject_type TEXT NOT NULL,
  subject_id   TEXT NOT NULL,
  UNIQUE(task_id, subject_type, subject_id)
);
CREATE INDEX IF NOT EXISTS idx_project_task_executors_subject
  ON project_task_executors(subject_type, subject_id);

-- ``parent_comment_id`` carries no FK on purpose -- readers tolerate a dangling
-- reference (PLAN §B3.1).
ALTER TABLE project_comments ADD COLUMN IF NOT EXISTS parent_comment_id TEXT;
ALTER TABLE project_comments ADD COLUMN IF NOT EXISTS quote_excerpt TEXT;
CREATE INDEX IF NOT EXISTS idx_project_comments_parent ON project_comments(parent_comment_id);

UPDATE _schema_version SET version = 27;
